"""Build an AK project with akt trace linked in, without changing the project.

The project's own Makefile is used as is. A generated wrapper makefile includes it, moves
OBJECTS_DIR to a cache folder and adds:

- akscope/firmware/akt/akt_trace.c
- a generated akt_auto.c with one __wrap_ function per task handler, a wrap of the first
  polling function that also calls akt_trace_poll(), and a wrap of task_create() that turns
  on the DWT cycle counter and starts the trace
- --wrap linker flags for those symbols and for task_post_*, timer_set, timer_remove_attr

The handler list comes from the relocations of .rodata.app_task_table in task_list.o, so it
works for C and C++ handlers and needs no parsing of the source.
"""

import concurrent.futures
import hashlib
import json
import os
import pathlib
import re
import shlex
import shutil
import subprocess

from akscope.core import symbols as symbols_mod

AKT_DIR = pathlib.Path(__file__).resolve().parent / "firmware" / "akt"
CACHE_ROOT = pathlib.Path(os.environ.get("XDG_CACHE_HOME", pathlib.Path.home() / ".cache")) / "akscope"

KERNEL_POST_WRAPS = ("task_post_pure_msg", "task_post_common_msg", "task_post_dynamic_msg",
                     "timer_set", "timer_remove_attr", "task_create")

# handlers that belong to the kernel and are not traced
KERNEL_HANDLERS = {"task_timer_tick"}

_WRAPPER_MK = """\
# generated by akscope build, do not edit

# before the include: the link rule expands $(OBJECTS) as soon as it is read, and the AK
# Makefile only appends to SOURCES (+= and :=), so these stay in the list
ifeq ($(AKT),1)
SOURCES += {akt}/akt_trace.c {gen}/akt_auto.c
VPATH += {akt} {gen}
endif

include Makefile

akscope-gcc-path:
\t@echo $(GCC_PATH)

akscope-print-%:
\t@echo $($*)

ifeq ($(AKT),1)
CFLAGS += -I{akt}
$(OBJECTS_DIR)/akt_trace.o $(OBJECTS_DIR)/akt_auto.o: CFLAGS += -DAKT_TRACE_EN $(AKT_DEFS)
LDFLAGS += $(foreach s,$(AKT_WRAP),--wrap=$(s))
endif
"""

_AUTO_HEAD = """\
/* generated by akscope build from {table}, do not edit */
#include <stdint.h>
#include <string.h>

#include "ak.h"
#include "task.h"
#include "stm32l1xx.h"

#include "akt_trace.h"

static uint32_t akt_auto_cycle_now(void) {{
	return DWT->CYCCNT;
}}

extern void __real_task_create(task_t* task_tbl);

/* called by main_app() inside ENTRY_CRITICAL(), AK critical sections nest */
void __wrap_task_create(task_t* task_tbl) {{
	akt_port_t port;
	uint8_t count = 0;

	__real_task_create(task_tbl);

	while (task_tbl[count].task != (pf_task)0) {{
		count++;
	}}

	CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
	DWT->CYCCNT = 0;
	DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;

	port.cycle_now = akt_auto_cycle_now;
	port.cpu_hz = SystemCoreClock;
	port.task_count = count;
	{app_ver_code}
#if defined(RELEASE)
	port.flags = AKT_FLAG_RELEASE;
#else
	port.flags = 0;
#endif
	akt_trace_init(&port);
}}
"""

_AUTO_HANDLER = """
extern void __real_{sym}(ak_msg_t* msg);
void __wrap_{sym}(ak_msg_t* msg) {{
	uint32_t t_begin = akt_exec_begin(msg);
	__real_{sym}(msg);
	akt_exec_end(t_begin);
}}
"""

_AUTO_POLLING = """
extern void __real_{sym}(void);
void __wrap_{sym}(void) {{
	__real_{sym}();
	akt_trace_poll();
}}
"""


class BuildError(Exception):
    pass


def find_application_dir(path):
    path = pathlib.Path(path).expanduser().resolve()
    for cand in (path, path / "application"):
        if (cand / "Makefile").is_file() and (cand / "sources" / "ak").is_dir():
            return cand
    raise BuildError("%s: no AK application (Makefile and sources/ak) found" % path)


def cache_dir(app_dir):
    tag = hashlib.sha1(str(app_dir).encode()).hexdigest()[:8]
    return CACHE_ROOT / "build" / ("%s-%s" % (app_dir.parent.name, tag))


def parse_relocations(text):
    """Symbols from `objdump -r` output, in offset order."""
    syms = []
    for line in text.splitlines():
        m = re.match(r"^[0-9a-f]+\s+R_ARM_ABS32\s+(\S+)$", line.strip())
        if m:
            syms.append(m.group(1))
    return syms


def table_symbols(objdump, obj, section):
    """Symbols referenced from one data section of an object file, in table order."""
    out = subprocess.run([objdump, "-r", "-j", section, str(obj)], capture_output=True,
                         text=True)
    if out.returncode != 0:
        return None
    return parse_relocations(out.stdout)


def undefined_symbols(nm, obj):
    out = subprocess.run([nm, "-u", str(obj)], capture_output=True, text=True, check=True)
    return {line.split()[-1] for line in out.stdout.splitlines() if line.strip()}


def generate_auto(handlers, polling, table_name, app_ver=None):
    if app_ver:
        app_ver_code = "\n\t".join("port.app_ver[%d] = %d;" % (i, v) for i, v in enumerate(app_ver))
    else:
        app_ver_code = "memset(port.app_ver, 0, sizeof(port.app_ver));"
    parts = [_AUTO_HEAD.format(table=table_name, app_ver_code=app_ver_code)]
    parts += [_AUTO_HANDLER.format(sym=s) for s in handlers]
    if polling:
        parts.append(_AUTO_POLLING.format(sym=polling))
    return "".join(parts)


# toolchain folder name the AK Makefiles expect under WORKSPACE_TOOLS_PATH
AK_GCC_SUBDIR = "gcc-arm-none-eabi-10.3-2021.10-x86_64-linux/gcc-arm-none-eabi-10.3-2021.10"


class Builder:
    def __init__(self, project, tools=None, gcc=None, ring=None, jobs=None, log=print):
        self.app = find_application_dir(project)
        self.cache = cache_dir(self.app)
        self.obj = self.cache / "obj"
        self.gen = self.cache / "gen"
        self.mk = self.cache / "akscope.mk"
        # toolchain paths given once are kept with the cache, so later commands need not repeat them
        saved = self._saved_config()
        tools = tools or saved.get("tools")
        gcc = gcc or saved.get("gcc")
        self.tools = pathlib.Path(tools).expanduser().resolve() if tools else None
        self.gcc = pathlib.Path(gcc).expanduser().resolve() if gcc else None
        # some projects set GCC_PATH to a fixed folder instead of using WORKSPACE_TOOLS_PATH
        if self.gcc is None and self.tools and (self.tools / AK_GCC_SUBDIR).is_dir():
            self.gcc = self.tools / AK_GCC_SUBDIR
        self.ring = ring
        self.jobs = jobs or os.cpu_count() or 1
        self.log = log

    def _make(self, *goals, **variables):
        cmd = ["make", "--no-print-directory", "-C", str(self.app), "-f", str(self.mk),
               "OBJECTS_DIR=%s" % self.obj, "-j%d" % self.jobs]
        if self.tools:
            cmd.append("WORKSPACE_TOOLS_PATH=%s" % self.tools)
        if self.gcc:
            cmd.append("GCC_PATH=%s" % self.gcc)
        cmd += ["%s=%s" % kv for kv in variables.items()]
        cmd += goals
        out = subprocess.run(cmd, capture_output=True, text=True)
        if out.returncode != 0:
            raise BuildError("make failed:\n%s%s" % (out.stdout[-3000:], out.stderr[-3000:]))
        return out.stdout

    def _saved_config(self):
        try:
            return json.loads((self.cache / "config.json").read_text())
        except (OSError, ValueError):
            return {}

    def prepare(self):
        self.gen.mkdir(parents=True, exist_ok=True)
        self.obj.mkdir(parents=True, exist_ok=True)
        self.mk.write_text(_WRAPPER_MK.format(akt=AKT_DIR, gen=self.gen))
        cfg = {"tools": str(self.tools) if self.tools else None, "gcc": str(self.gcc) if self.gcc else None}
        (self.cache / "config.json").write_text(json.dumps(cfg))

    def build(self):
        self.prepare()
        gcc_path = self._make("akscope-gcc-path").strip().splitlines()[-1]
        objdump = pathlib.Path(gcc_path) / "bin" / "arm-none-eabi-objdump"
        nm = pathlib.Path(gcc_path) / "bin" / "arm-none-eabi-nm"
        if not objdump.is_file():
            raise BuildError("toolchain not found at %s, pass --tools <folder holding "
                             "gcc-arm-none-eabi-...> or --gcc <toolchain folder>" % gcc_path)

        # pass 1: only the task table object, to read which handlers it points to
        task_list_o = self.obj / "task_list.o"
        self.log("akscope: reading task table")
        self._make(str(task_list_o), AKT=0)

        handlers = table_symbols(objdump, task_list_o, ".rodata.app_task_table")
        polling = table_symbols(objdump, task_list_o, ".rodata.app_task_polling_table")
        if handlers is None:
            raise BuildError("task_list.o has no app_task_table section")

        # --wrap only redirects references between objects; a handler defined inside
        # task_list.cpp itself cannot be traced
        external = undefined_symbols(nm, task_list_o)
        skipped = [s for s in handlers if s not in external]
        handlers = [s for s in handlers if s in external and s not in KERNEL_HANDLERS]
        polling_sym = next((s for s in (polling or []) if s in external), None)
        if polling_sym is None:
            raise BuildError("no polling task to carry the trace output")
        for s in skipped:
            if s not in KERNEL_HANDLERS:
                self.log("akscope: %s is defined in task_list.cpp, not traced" % s)

        syms = self.extract_symbols()
        (self.gen / "akt_auto.c").write_text(generate_auto(handlers, polling_sym,
                                                          "app_task_table", syms["app_ver"]))
        wraps = list(KERNEL_POST_WRAPS) + handlers + [polling_sym]

        # pass 2: the whole firmware with akt
        self.log("akscope: building with akt trace, %d handlers" % len(handlers))
        defs = "-DAKT_RING_SIZE=%d" % self.ring if self.ring else ""
        # akt objects do not depend on the flags, rebuild them so a new --ring applies
        for o in ("akt_trace.o", "akt_auto.o"):
            (self.obj / o).unlink(missing_ok=True)
        out = self._make("all", AKT=1, AKT_WRAP=" ".join(wraps), AKT_DEFS=defs)
        bins = sorted(self.obj.glob("*.bin"))
        if not bins:
            raise BuildError("build finished but no .bin in %s" % self.obj)
        for line in out.splitlines():
            if "Flash info" in line or "RAM info" in line:
                self.log(line.strip())
        return bins[0], handlers

    @property
    def symbols_path(self):
        return self.cache / "symbols.json"

    def _var(self, name):
        return self._make("akscope-print-%s" % name).strip()

    def _preprocess(self, compiler, flags, src, macros=False):
        cmd = [compiler] + flags + (["-dM"] if macros else []) + ["-E", src]
        out = subprocess.run(cmd, cwd=self.app, capture_output=True, text=True, errors="replace")
        if out.returncode != 0:
            raise BuildError("preprocessing %s failed:\n%s" % (src, out.stderr[-2000:]))
        return out.stdout

    def preprocess(self, prefixes, extra=()):
        """{source path: -E output} for the built sources under prefixes, plus extra paths.

        Uses the project's own compiler and flags, so #if and macros resolve as in the build.
        """
        drop = {"-c", "-MD", "-MMD", "-fstack-usage"}
        cxx = self._var("CPP")
        cc = self._var("CC")
        cxx_flags = [f for f in shlex.split(self._var("CPPFLAGS")) if f not in drop]
        c_flags = [f for f in shlex.split(self._var("CFLAGS")) if f not in drop]
        files = shlex.split(self._var("SOURCES_CPP")) + shlex.split(self._var("SOURCES"))
        files = [f for f in files if f.startswith(tuple(prefixes)) or f in extra]

        def run(src):
            if src.endswith(".cpp"):
                return src, self._preprocess(cxx, cxx_flags, src)
            return src, self._preprocess(cc, c_flags, src)

        with concurrent.futures.ThreadPoolExecutor(self.jobs) as pool:
            texts = dict(pool.map(run, files))
        self._macro_flags = (cxx, cxx_flags)
        return texts

    def macros(self, src):
        """`-dM -E` output for one C++ source, after preprocess() ran."""
        cxx, flags = self._macro_flags
        return self._preprocess(cxx, flags, src, True)

    def extract_symbols(self):
        """Task and signal names from the app sources, written to symbols.json."""
        self.log("akscope: reading task and signal names")
        # signals are used in app, the link/rf stacks under networks, drivers, and the
        # screen manager in common (it arms the display render timer)
        texts = self.preprocess(("sources/app/", "sources/networks/", "sources/driver/",
                                 "sources/common/"))
        task_list = next((t for f, t in texts.items() if f.endswith("/task_list.cpp")), None)
        if task_list is None:
            raise BuildError("sources/app/task_list.cpp not in the build")
        app_ver = None
        app_cpp = next((f for f in texts if f.endswith("/app.cpp")), None)
        if app_cpp:
            app_ver = symbols_mod.parse_app_ver(self.macros(app_cpp))

        others = [t for f, t in texts.items() if not f.endswith("/task_list.cpp")]
        syms = symbols_mod.build_symbols(task_list, others, app_ver)
        syms["project"] = str(self.app.parent)
        self.symbols_path.write_text(json.dumps(syms, indent=1, sort_keys=True))
        named = sum(len(v) for v in syms["signals"].values())
        self.log("akscope: %d tasks, %d task signals named" % (len(syms["tasks"]), named))
        return syms

    def clean(self):
        shutil.rmtree(self.cache, ignore_errors=True)
