"""Take design data out of the Figma design system file, so the UI follows the file instead
of hand copied values.

    python3 tools/figma_export.py tokens FILE.fig [-o akscope/web/theme/figma-tokens.css]
    python3 tools/figma_export.py icons FILE.fig NAME... [-o akscope/web/icons]
    python3 tools/figma_export.py render FILE.fig NODE_NAME -o out.png [--page PAGE]
    python3 tools/figma_export.py all FILE.fig      # tokens, icons, spec, with the lists below

tokens  every variable of the color set (modes default-dark and default-light) and the number
        sets (radius, spacing, typography) as CSS custom properties
icons   the named icons of the Icon page as SVG, filled with currentColor
render  one frame or component drawn as PNG, the reference for visual checks
spec    every component variant on the given pages: size, auto layout, radius, paints with
        the variable they are bound to, effects, and the text styles inside, as JSON
"""

import argparse
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import figkit  # noqa: E402

COLOR_SET = "1. Color mode"

ROOT = pathlib.Path(__file__).resolve().parent.parent
ICON_LIST = ROOT / "tools" / "figma_icons.txt"
# the component pages the UI is built from
SPEC_PAGES = ("Button", "Tabs", "Table", "Tree", "Tag", "Tooltip", "Select", "Input ", "Check box", "Segmented",
              "Switch", "Badge", "Alert", "Message", "Modal", "Drawer", "Empty", "Statistic", "Navbar",
              "Dropdown", "Menu", "Pagination", "Collapse", "Progress", "Popover confirm", "Upload", "Radio button",
              "Breadcrumb")
MODES = {"default-dark": "dark", "default-light": "light"}


def css_name(var_name):
    """color/background/base -> --color-background-base"""
    s = re.sub(r"[^A-Za-z0-9]+", "-", var_name.strip()).strip("-").lower()
    return "--" + s


def _rgba(c):
    a = c.get("a", 1)
    hexc = figkit.color_hex(c)
    if a >= 0.999:
        return hexc
    return "rgba(%d, %d, %d, %.3g)" % (round(c["r"] * 255), round(c["g"] * 255), round(c["b"] * 255), a)


def _sets(doc):
    return {k: n for k, n in doc.nodes.items() if n.get("type") == "VARIABLE_SET"}


def _color_set(doc):
    """The color set the components are painted with (the most used one of that name)."""
    sets = [k for k, n in _sets(doc).items() if n.get("name") == COLOR_SET]
    use = {k: 0 for k in sets}
    for n in doc.nodes.values():
        for p in (n.get("fillPaints") or []) + (n.get("strokePaints") or []):
            a = ((p.get("colorVar") or {}).get("value") or {}).get("alias") or {}
            v = doc.variables.get(figkit.gid(a["guid"])) if "guid" in a else None
            if v and "guid" in v.get("variableSetID", {}) and figkit.gid(v["variableSetID"]["guid"]) in use:
                use[figkit.gid(v["variableSetID"]["guid"])] += 1
    return max(use, key=use.get)


def tokens(doc):
    sets = _sets(doc)
    cset = _color_set(doc)
    modes = {figkit.gid(m["id"]): MODES.get(m["name"], m["name"]) for m in sets[cset]["variableSetModes"]}
    blocks = {mode: {} for mode in modes.values()}
    numbers = {}
    for v in doc.variables.values():
        name = v.get("name", "")
        if "guid" not in (v.get("variableSetID") or {}):
            continue  # a variable of a library the file only links to
        set_id = figkit.gid(v["variableSetID"]["guid"])
        if set_id == cset:
            for mode_id, mode in modes.items():
                val = doc.resolve(v["guid"], {cset: mode_id})
                if val and "colorValue" in val:
                    blocks[mode][css_name(name)] = _rgba(val["colorValue"])
        elif set_id in sets and sets[set_id].get("name", "").split(". ")[-1] in ("Radius", "Spacing", "Width", "Typographic", "Icon"):
            val = doc.resolve(v["guid"], {})
            if val and "floatValue" in val:
                numbers[css_name(name)] = "%gpx" % val["floatValue"]
            elif val and "textValue" in val:
                numbers[css_name(name)] = val["textValue"]
    out = ["/* generated by tools/figma_export.py from the Figma design system, do not edit */", ""]
    out.append(":root {")
    out += ["\t%s: %s;" % kv for kv in sorted(numbers.items())]
    out.append("}")
    # on any element too, so a part of a page can be in the other mode (the gallery shows both)
    for mode, sel in (("dark", ':root,\n[data-theme="dark"]'), ("light", '[data-theme="light"]')):
        out.append("")
        out.append("%s {" % sel)
        out += ["\t%s: %s;" % kv for kv in sorted(blocks.get(mode, {}).items())]
        out.append("}")
    return "\n".join(out) + "\n"


def icon_svg(doc, renderer, node):
    """An icon as SVG with currentColor in place of its paint colors."""
    svg = renderer.svg(node)
    svg = re.sub(r'(fill)="#[0-9a-f]{6}"', r'\1="currentColor"', svg)
    return svg


def icons(doc, names, out_dir):
    """names are icon names, "name:bold" for the bold style (written as name-bold.svg)"""
    page = doc.page("ICON")
    # the icons are the direct children of the big "Icon" frame; other frames on the page
    # reuse some names (a "flash" toggle, for one), and a few names are there twice, once empty
    sheet = next(n for n in doc.kids(page) if n.get("name") == "Icon")
    def styled(n):
        return any("=" in v.get("name", "") for v in doc.kids(n))

    frames = {}
    for n in doc.kids(sheet):
        if n.get("name") not in frames or (styled(n) and not styled(frames[n["name"]])):
            frames[n["name"]] = n
    r = figkit.Renderer(doc)
    out_dir.mkdir(parents=True, exist_ok=True)
    missing = []
    for item in sorted(set(names)):
        name, _, style = item.partition(":")
        n = frames.get(name)
        if n is None:
            # a few icons are components of their own outside the sheet ("Close" of the modal); the
            # outline of "Close" is only in the derived data of its instances, so one is drawn
            inst = next((v for v in doc.nodes.values() if v.get("type") == "INSTANCE" and v.get("name") == name
                         and v.get("derivedSymbolData")), None)
            if inst is None:
                missing.append(item)
            else:
                (out_dir / ("%s.svg" % name.lower())).write_text(icon_svg(doc, r, inst) + "\n")
            continue
        # each icon frame holds a bold and an outline variant ("Style=outline", "Property 1=bold", ...)
        style = style or "outline"
        variants = doc.kids(n)
        pick = next((v for v in variants if v.get("name", "").lower().endswith("=" + style)), None)
        if pick is None and style == "outline":
            # "minus" names its outline variant "Style=Style3"
            pick = next((v for v in variants if not v.get("name", "").lower().endswith("=bold")), None)
        if pick is None:
            missing.append(item)
            continue
        fname = name if style == "outline" else "%s-%s" % (name, style)
        (out_dir / ("%s.svg" % fname)).write_text(icon_svg(doc, r, pick) + "\n")
    return missing


def _var_name(doc, paint):
    a = ((paint.get("colorVar") or {}).get("value") or {}).get("alias") or {}
    v = doc.variables.get(figkit.gid(a["guid"])) if "guid" in a else None
    return css_name(v["name"]) if v else None


def _paints(doc, paints):
    out = []
    for p in paints or []:
        if not p.get("visible", 1):
            continue
        item = {"type": p.get("type"), "opacity": round(p.get("opacity", 1), 3)}
        if p.get("type") == "SOLID":
            item["color"] = _rgba(p.get("color", {}))
            var = _var_name(doc, p)
            if var:
                item["var"] = var
        out.append(item)
    return out


def _box(doc, n):
    s = n.get("size", {})
    t = n.get("transform", {})
    d = {"name": n.get("name"), "type": n.get("type"), "w": round(s.get("x", 0), 2), "h": round(s.get("y", 0), 2),
         "x": round(t.get("m02", 0), 2), "y": round(t.get("m12", 0), 2)}
    if n.get("stackMode"):
        d["layout"] = {"mode": n["stackMode"], "gap": n.get("stackSpacing", 0),
                       "pad": [n.get("stackVerticalPadding", 0), n.get("stackPaddingRight", n.get("stackHorizontalPadding", 0)),
                               n.get("stackPaddingBottom", n.get("stackVerticalPadding", 0)), n.get("stackHorizontalPadding", 0)],
                       "main": n.get("stackPrimaryAlignItems"), "cross": n.get("stackCounterAlignItems")}
    radius = [n.get(k) for k in ("rectangleTopLeftCornerRadius", "rectangleTopRightCornerRadius",
                                 "rectangleBottomRightCornerRadius", "rectangleBottomLeftCornerRadius")]
    if any(radius):
        d["radius"] = radius if len(set(radius)) > 1 else radius[0]
    elif n.get("cornerRadius"):
        d["radius"] = n["cornerRadius"]
    if n.get("fillPaints"):
        d["fill"] = _paints(doc, n["fillPaints"])
    if n.get("strokePaints") and n.get("strokeWeight"):
        d["stroke"] = _paints(doc, n["strokePaints"])
        d["stroke_weight"] = n["strokeWeight"]
        d["stroke_align"] = n.get("strokeAlign")
        if n.get("borderStrokeWeightsIndependent"):
            # top, right, bottom, left
            d["stroke_sides"] = [n.get("border%sWeight" % k, 0) for k in ("Top", "Right", "Bottom", "Left")]
        if n.get("dashPattern"):
            d["dash"] = n["dashPattern"]
    fx = [e for e in n.get("effects") or [] if e.get("visible", 1)]
    if fx:
        d["effects"] = [{"type": e.get("type"), "x": e.get("offset", {}).get("x", 0), "y": e.get("offset", {}).get("y", 0),
                         "blur": e.get("radius", 0), "spread": e.get("spread", 0), "color": _rgba(e.get("color", {}))} for e in fx]
    if n.get("type") == "TEXT":
        f = n.get("fontName", {})
        lh = n.get("lineHeight") or {}
        # what Figma shows is the laid out text: per character styles can override the node's
        # own font size (a "Button" label is 16 on the node and drawn at 14)
        derived = n.get("derivedTextData") or {}
        glyphs = derived.get("glyphs") or []
        meta = (derived.get("fontMetaData") or [{}])[0].get("key") or {}
        size = glyphs[0]["fontSize"] if glyphs else n.get("fontSize")
        d["text"] = {"chars": (n.get("textData") or {}).get("characters", ""),
                     "family": meta.get("family") or f.get("family"), "style": meta.get("style") or f.get("style"),
                     "size": size, "node_size": n.get("fontSize"),
                     "width": round((derived.get("baselines") or [{}])[0].get("width", 0), 3),
                     "line_height": [lh.get("value"), lh.get("units")],
                     "letter_spacing": [(n.get("letterSpacing") or {}).get("value"), (n.get("letterSpacing") or {}).get("units")]}
    if n.get("opacity", 1) < 1:
        d["opacity"] = round(n["opacity"], 3)
    if not n.get("visible", 1):
        d["hidden"] = True
    if n.get("type") == "INSTANCE" and (n.get("symbolData") or {}).get("symbolID"):
        sym = doc.nodes.get(figkit.gid(n["symbolData"]["symbolID"]))
        if sym:
            d["of"] = sym.get("name")
    kids = [_box(doc, c) for c in doc.kids(n)]
    if kids:
        d["children"] = kids
    return d


def spec(doc, pages):
    out = {}
    for name in pages:
        page = doc.page(name)
        comps = []
        for n in doc.walk(page):
            if n.get("type") == "SYMBOL":
                parent = doc.nodes.get(figkit.gid(n["parentIndex"]["guid"])) if n.get("parentIndex") else None
                d = _box(doc, n)
                d["set"] = parent.get("name") if parent and parent.get("type") != "CANVAS" else None
                comps.append(d)
        out[page.get("name", name).strip()] = comps
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("tokens")
    t.add_argument("fig")
    t.add_argument("-o", "--output", default="akscope/web/theme/figma-tokens.css")
    i = sub.add_parser("icons")
    i.add_argument("fig")
    i.add_argument("names", nargs="+")
    i.add_argument("-o", "--output", default="akscope/web/icons")
    r = sub.add_parser("render")
    r.add_argument("fig")
    r.add_argument("node")
    r.add_argument("--page")
    r.add_argument("-o", "--output", required=True)
    r.add_argument("--scale", type=float, default=1)
    sp = sub.add_parser("spec")
    sp.add_argument("fig")
    sp.add_argument("pages", nargs="+")
    sp.add_argument("-o", "--output", default="tests/figma/figma-spec.json")
    a = sub.add_parser("all")
    a.add_argument("fig")
    args = ap.parse_args(argv)

    doc = figkit.Doc(args.fig)
    if args.cmd == "all":
        (ROOT / "akscope/web/theme/figma-tokens.css").write_text(tokens(doc))
        names = [l.strip() for l in ICON_LIST.read_text().splitlines() if l.strip()]
        missing = icons(doc, names, ROOT / "akscope/web/icons")
        (ROOT / "tests/figma/figma-spec.json").write_text(
            json.dumps(spec(doc, SPEC_PAGES), indent=1, ensure_ascii=False) + "\n")
        print("tokens, %d icons, spec written" % (len(names) - len(missing)))
        return 1 if missing else 0
    if args.cmd == "tokens":
        pathlib.Path(args.output).write_text(tokens(doc))
        print(args.output)
    elif args.cmd == "spec":
        pathlib.Path(args.output).write_text(json.dumps(spec(doc, args.pages), indent=1, ensure_ascii=False) + "\n")
        print(args.output)
    elif args.cmd == "icons":
        missing = icons(doc, args.names, pathlib.Path(args.output))
        if missing:
            print("not found:", " ".join(missing), file=sys.stderr)
            return 1
    else:
        root = doc.page(args.page) if args.page else None
        pool = doc.walk(root) if root else doc.nodes.values()
        node = next((n for n in pool if n.get("name") == args.node), None)
        if node is None:
            print("no node named %r" % args.node, file=sys.stderr)
            return 1
        figkit.svg_to_png(figkit.Renderer(doc).svg(node), args.output, args.scale)
        print(args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
